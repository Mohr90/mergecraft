// Inject with MERGECRAFT_SELFTEST; run only against a disposable test repository.
(async()=>{
  const invoke=window.__TAURI__.core.invoke;
  const wait=ms=>new Promise(r=>setTimeout(r,ms));
  const until=async(fn)=>{for(let i=0;i<150;i++){if(fn())return;await wait(100);}throw new Error('Timeout: '+fn);};
  const click=selector=>{const node=document.querySelector(selector);if(!node)throw new Error('Missing '+selector);node.click();};
  const assert=(ok,message)=>{if(!ok)throw new Error(message);};
  const log=[];
  try{
    await until(()=>document.querySelector('.branches-panel'));
    const panelLeft=document.querySelector('.panel-wrap').getBoundingClientRect().left;
    assert(document.querySelector('.titlebar .brand').getBoundingClientRect().left<panelLeft,'brand not at upper left');
    assert(document.querySelector('.workspace-toolbar .repo-name').getBoundingClientRect().left>=panelLeft,'project context still above sidebar');
    const firstRow=document.querySelector('.branch-row');const rowTop=firstRow.getBoundingClientRect().top;
    click('.branch-more summary');await until(()=>document.querySelector('.branch-more[open]'));
    const popup=document.querySelector('.branch-more[open] .branch-more-menu');const bounds=popup.getBoundingClientRect();
    assert(firstRow.getBoundingClientRect().top===rowTop,'menu moved branch row');
    assert(bounds.left>=0&&bounds.right<=innerWidth&&bounds.top>=0&&bounds.bottom<=innerHeight,'native menu outside viewport');
    assert(popup.contains(document.elementFromPoint(bounds.left+20,bounds.top+20)),'native menu is clipped');
    document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true}));
    assert(!document.querySelector('.branch-more[open]'),'Escape did not close native menu');
    log.push('PASS native header layout and compact branch menu without row movement');

    click('[data-branch-act="create"]');await until(()=>document.querySelector('dialog[open] input'));
    const input=document.querySelector('dialog input');input.value='feature/gui-test';click('dialog [data-v="ok"]');
    await until(()=>document.querySelector('.branch-trigger .name')?.textContent==='feature/gui-test');log.push('PASS create branch through dialog');
    click('.branch-row[data-name="main"] [data-b-act="checkout"]');
    await until(()=>document.querySelector('.branch-trigger .name')?.textContent==='main');log.push('PASS switch branch');
    click('[data-tab="tags"]');await until(()=>document.querySelectorAll('.tag-row').length===2);
    click('[data-tag-name="release/base"] [data-tag-act="commit"]');
    await until(()=>document.querySelector('.hist-side .commit-head'));
    click('[data-tab="tags"]');click('[data-tag-name="release/base"] [data-tag-act="compare"]');
    await until(()=>document.querySelector('.compare-host:not(.hidden) [data-compare-file]'));click('[data-compare-close]');
    click('[data-tag-name="release/base"] [data-tag-act="branch"]');await until(()=>document.querySelector('dialog[open] input'));
    document.querySelector('dialog input').value='feature/from-tag';click('dialog [data-v="ok"]');
    await until(()=>document.querySelector('.branch-trigger .name')?.textContent==='feature/from-tag');
    const tagHash=await invoke('git_raw',{args:['rev-parse','refs/tags/release/base^{commit}']});
    assert((await invoke('snapshot')).head===tagHash.stdout.trim(),'new branch not at tag commit');
    click('.branch-row[data-name="main"] [data-b-act="checkout"]');await until(()=>document.querySelector('.branch-trigger .name')?.textContent==='main');
    log.push('PASS tags list, commit, comparison and branch from tag');
    const pushing=invoke('push',{set_upstream:true});
    await wait(150);
    const responsive=await Promise.race([invoke('set_title',{title:'Mergecraft remote responsiveness test'}).then(()=>true),wait(600).then(()=>false)]);
    assert(responsive,'window commands blocked by slow push');
    assert((await pushing).ok,'local test push failed');
    assert((await invoke('fetch_remote',{remote:null})).ok,'local test fetch failed');
    assert((await invoke('pull')).ok,'local test pull failed');
    log.push('PASS responsive push, fetch and pull against disposable local remote');
    click('[data-act="refresh"]');await until(()=>!document.querySelector('.shell.busy'));
    assert(document.querySelector('[data-sync-state="ok"]'),'published branch not shown synchronized');
    await invoke('git_raw',{args:['commit','--allow-empty','-m','native pending push']});
    click('[data-act="refresh"]');await until(()=>!document.querySelector('.shell.busy')&&document.querySelector('[data-sync-state="pending"]'));
    assert(document.querySelector('[data-sync-state="pending"]').textContent.includes('ungepushter'),'local commit not shown pending');
    click('[data-act="push"]');await until(()=>!document.querySelector('.shell.busy')&&document.querySelector('[data-sync-state="ok"]'));
    log.push('PASS local commit shown unpushed and successful real push updates synchronization status');

    click('.branch-row[data-name="feature/source"] [data-b-act="compare"]');
    await until(()=>document.querySelector('.compare-host:not(.hidden) [data-compare-file]'));
    click('[data-compare-file]');await until(()=>document.querySelector('.diff-host:not(.hidden) .diff'));
    click('.diff [data-act="close"]');await until(()=>document.querySelector('.compare-host:not(.hidden)'));
    click('[data-compare-close]');log.push('PASS branch comparison and file diff');
    assert(!document.querySelector('[data-b-act="merge"]'),'main still offers local merge');
    click('.branch-row[data-name="feature/gui-test"] [data-b-act="checkout"]');await until(()=>document.querySelector('.branch-trigger .name')?.textContent==='feature/gui-test');
    click('.branch-row[data-name="feature/source"] [data-b-act="merge"]');await until(()=>document.querySelector('dialog[open]'));click('dialog [data-i="1"]');
    await until(()=>document.querySelector('.merge-host:not(.hidden) .merge'));
    assert(document.querySelector('.merge-head .name').textContent==='a.txt','first conflict is text');
    click('.merge [data-act="raw"]');document.querySelector('.raw-edit').value='native resolved\n';document.querySelector('.raw-edit').dispatchEvent(new Event('input'));
    click('.merge [data-act="save"]');await wait(800);
    click('.merge [data-act="close"]');await until(()=>!document.querySelector('.panel.hidden'));
    click('[data-row-act="merge"]');await until(()=>document.querySelector('.merge-host:not(.hidden) .raw-edit'));
    assert(document.querySelector('.raw-edit').value==='native resolved\n','saved resolution reloaded');log.push('PASS save and reopen manual resolution');
    click('.merge [data-act="save-resolve"]');await until(()=>document.querySelector('.merge-host:not(.hidden) [data-act="whole-theirs"]'));
    click('[data-act="whole-theirs"]');await until(()=>document.querySelector('dialog[open]'));click('dialog [data-i="1"]');
    await until(()=>document.querySelector('[data-top-act="merge-continue"]'));log.push('PASS text and binary conflicts resolved');
    click('[data-top-act="merge-continue"]');await until(()=>!document.querySelector('[data-top-act="merge-continue"]')&&!document.querySelector('.shell.busy'));
    const status=await invoke('status');const snap=await invoke('snapshot');
    assert(!snap.merging&&status.conflicts.length===0,'merge completed');
    log.push('PASS merge commit completed');
    await invoke('save_conflict',{path:'a.txt',text:'discard staged\n',mark_resolved:true});
    await invoke('save_conflict',{path:'a.txt',text:'discard working\n',mark_resolved:false});
    const stagedDiff=await invoke('working_diff',{path:'a.txt',area:'staged'});
    const workDiff=await invoke('working_diff',{path:'a.txt',area:'work'});
    assert(stagedDiff.b_text==='discard staged\n','staged diff shows worktree instead of index');
    assert(workDiff.a_text==='discard staged\n'&&workDiff.b_text==='discard working\n','work diff does not compare index to worktree');
    assert((await invoke('file_history',{path:'a.txt'})).length>0,'file history empty');
    log.push('PASS exact staged/worktree diffs and file history');

    await invoke('save_conflict',{path:'parking-new.txt',text:'new file\n',mark_resolved:false});
    const beforeStashes=(await invoke('stashes')).map(stash=>stash.oid).join(',');
    click('[data-act="refresh"]');await until(()=>document.querySelector('.row[data-path="a.txt"] [data-row-act="rollback"]'));
    click('.row[data-path="a.txt"][data-area="staged"] .fpath');
    await until(()=>document.querySelector('.changes-preview .diff'));
    assert(document.querySelector('.changes-preview .diff').textContent.includes('discard staged'),'inline staged preview missing index text');
    click('.row[data-path="a.txt"][data-area="work"] .fpath');
    await until(()=>document.querySelector('.changes-preview .diff')?.textContent.includes('discard working'));
    log.push('PASS native inline preview switches staged and worktree contents');
    const mixed=document.querySelector('[data-stage-all]');assert(mixed.indeterminate,'mixed all-files checkbox missing');
    click('.row[data-path="a.txt"][data-area="staged"] [data-stage-file]');
    await until(()=>!document.querySelector('.shell.busy')&&!document.querySelector('.row[data-path="a.txt"][data-area="staged"]'));
    assert((await invoke('working_diff',{path:'a.txt',area:'work'})).b_text==='discard working\n','unchecking changed worktree content');
    click('.row[data-path="a.txt"][data-area="work"] [data-stage-file]');
    await until(()=>!document.querySelector('.shell.busy')&&document.querySelector('.row[data-path="a.txt"][data-area="staged"]'));
    assert((await invoke('working_diff',{path:'a.txt',area:'staged'})).b_text==='discard working\n','checking did not update index');
    assert((await invoke('status')).untracked.some(file=>file.path==='parking-new.txt'),'checkbox staged unrelated new file');
    log.push('PASS native staging checkboxes preserve worktree and update only selected index entry');


    click('.row[data-path="a.txt"] [data-row-act="rollback"]');await until(()=>document.querySelector('dialog[open]'));click('dialog [data-i="1"]');
    await until(()=>!document.querySelector('.shell.busy')&&!document.querySelector('.row[data-path="a.txt"]'));
    assert((await invoke('stashes')).map(stash=>stash.oid).join(',')===beforeStashes,'rollback created a stash');
    assert((await invoke('status')).untracked.some(file=>file.path==='parking-new.txt'),'rollback removed untracked file');
    assert(!document.querySelector('[data-top-act="stash-save"],.stash-section,.opt-all,.opt-sign,.opt-amend'),'removed controls still visible');
    const before=(await invoke('snapshot')).head;
    await invoke('save_conflict',{path:'a.txt',text:'new commit content\n',mark_resolved:true});
    click('[data-act="refresh"]');await until(()=>!document.querySelector('.shell.busy')&&document.querySelector('.row[data-area="staged"]'));
    assert(document.querySelector('.commit-mode').value==='new','default is not new commit');
    document.querySelector('.commit-msg').value='native new commit';click('[data-top-act="commit"]');
    await until(()=>!document.querySelector('.shell.busy')&&!document.querySelector('.row[data-path="a.txt"]'));
    const created=(await invoke('snapshot')).head;
    assert((await invoke('git_raw',{args:['rev-parse','HEAD^']})).stdout===before,'normal commit did not create a child');
    await invoke('save_conflict',{path:'a.txt',text:'amended content\n',mark_resolved:true});
    click('[data-act="refresh"]');await until(()=>!document.querySelector('.shell.busy')&&document.querySelector('.row[data-area="staged"]'));
    document.querySelector('.commit-mode').value='amend';document.querySelector('.commit-mode').dispatchEvent(new Event('change'));
    document.querySelector('.commit-msg').value='native amend';click('[data-top-act="commit"]');
    await until(()=>!document.querySelector('.shell.busy')&&!document.querySelector('.row[data-path="a.txt"]'));
    assert((await invoke('snapshot')).head!==created,'amend did not replace commit');
    assert((await invoke('git_raw',{args:['rev-parse','HEAD^']})).stdout===before,'amend created an extra commit');
    assert(document.querySelector('.commit-mode').value==='new','amend did not reset after success');
    assert((await invoke('status')).untracked.some(file=>file.path==='parking-new.txt'),'commit included untracked file');
    log.push('PASS new commit by default and explicit amend, only staged changes committed');
  }catch(e){log.push('FAIL '+(e.stack||e));}
  await invoke('selftest_report',{text:log.join('\n')});
})();
